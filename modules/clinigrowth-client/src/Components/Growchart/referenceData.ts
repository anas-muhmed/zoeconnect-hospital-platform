// Monthly resolution, transcribed from the official WHO percentile
// tables (cdn.who.int/.../child-growth-standards/indicators/...):
//   - weight-for-age, head-circumference-for-age: direct percentile
//     tables, birth to 60 months, both sexes.
//   - length/height-for-age: length-for-age (recumbent, 0-24mo) spliced
//     with height-for-age (standing, 24-60mo) at the 24-month boundary,
//     matching WHO's own convention.
//   - BMI-for-age: WHO publishes birth-to-2-years only as L/M/S z-score
//     parameters (no direct percentile table for that range), so the
//     0-24 month percentiles here are computed from those parameters via
//     WHO's standard LMS formula (X = M*(1+L*S*Z)^(1/L), with Z at the
//     standard-normal values for the 3rd/15th/50th/85th/97th percentiles);
//     25-60 months use WHO's direct percentile table. WHO's own
//     birth-to-2y and 2-to-5y BMI curves are independently fitted and
//     have a small documented discontinuity exactly at 24 months (from
//     switching recumbent-length-based to standing-height-based
//     measurement) -- this is inherent to WHO's source data, not a
//     transcription artifact; resolved here by using the 0-2y series
//     through month 24 and the 2-5y series from month 25 onward.
// x = 40 + month * 52/12 (weeks since LMP, matching the Fenton x-axis).
